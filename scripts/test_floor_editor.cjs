const fs=require('fs'),vm=require('vm'),assert=require('assert');
const html=fs.readFileSync('src/web_studio.html','utf8');
const context={config:{walkable_trapezoid:{back_x_min:100,back_x_max:1180,front_x_min:-240,front_x_max:1520,y_min:300,y_max:900}},Math,Number};
vm.createContext(context);
vm.runInContext(html.slice(html.indexOf('// Floor geometry remains convex'),html.indexOf('function validPoseGround')),context);
const original=context.floorPoints();
assert(original.every(([x,y])=>x>=0&&x<=1280&&y>=0&&y<=720),'Legacy floors are bounded when opened');
assert(context.validFloorPolygon(original));
const clipped=context.clipFloorToImage(original);
assert(clipped.length>4,'Trimming off-image corners must add visible edge vertices');
assert(clipped.every(([x,y])=>x>=0&&x<=1280&&y>=0&&y<=720));
assert(context.validFloorPolygon(clipped));
assert(context.setFloorPoints(clipped));
assert(context.insideFloor(640,600));assert(!context.insideFloor(-1,600));
const projected=context.clampToWalkable(-100,600);assert(context.insideFloor(projected.x,projected.y));
const crossed=[[0,0],[200,200],[0,200],[200,0]];assert(!context.setFloorPoints(crossed));
assert(!context.validFloorPolygon([[0,0],[100,0],[50,50],[100,100],[0,100]]),'Concave floor must be rejected by convex navigation model');
const split=context.floorPoints();split.splice(1,0,[(split[0][0]+split[1][0])/2,(split[0][1]+split[1][1])/2]);assert(context.setFloorPoints(split));
assert.equal(context.config.walkable_trapezoid.y_min,300,'Keep depth calibration while trimming floor');
context.mainContainer={clientWidth:1000,clientHeight:600};context.canvas={style:{},getBoundingClientRect:()=>({left:250,top:130})};
context.document={getElementById:()=>({textContent:''})};context.render=()=>{};
vm.runInContext('let zoom=1,panX=0,panY=0;',context);
vm.runInContext(html.slice(html.indexOf('function fitCanvas()'),html.indexOf('function getObstacleCorners')),context);
context.config.walkable_trapezoid.points=original;context.fitCanvas();
const state=vm.runInContext('({zoom,panX,panY})',context);
for(const [x,y] of original){const sx=state.panX+x*state.zoom,sy=state.panY+y*state.zoom;assert(sx>=30&&sx<=970&&sy>=30&&sy<=570,'Reset reveals every off-image corner');const p=context.getCanvasCoords({clientX:250+sx,clientY:130+sy});assert(Math.abs(p.x-x)<1e-6&&Math.abs(p.y-y)<1e-6);}
const event={clientX:700,clientY:430},before=context.getCanvasCoords(event);context.setZoomRelative(1.4,event.clientX,event.clientY);const after=context.getCanvasCoords(event);assert(Math.hypot(after.x-before.x,after.y-before.y)<1e-6,'Wheel zoom must stay anchored at pointer, including sidebar/header offsets');
console.log('Off-image fit, pointer transforms, zoom anchoring, clipping into extra vertices, convexity and pose bounds passed.');
const start=[[100,100],[1100,100],[1100,600],[100,600]];
context.config.walkable_trapezoid.points=start;context.beginFloorDrag(0);
assert(context.moveFloorCorner(-100,-100));
let during=context.floorPoints();assert(during.length>4);assert(during.some(([x,y])=>x===0&&y===0),'Crossing both boundaries inserts the image corner');
assert(during.every(([x,y])=>x>=0&&x<=1280&&y>=0&&y<=720));
assert(context.moveFloorCorner(-300,80));
assert.deepEqual(context.floorPoints(),context.clipFloorToImage([[-300,80],...start.slice(1)]),'Repeated drag uses original vertex despite added edge points');
assert(context.moveFloorCorner(120,120));assert.equal(context.floorPoints().length,4,'Dragging back in restores the same corner smoothly');
assert(!html.includes('id="clipFloorOnDrop"'),'Boundary clipping is mandatory');
console.log('Immediate clipping, image-corner insertion, continuous dragging and mandatory bounds passed.');
const redundant=[[0,0],[1280,0],[1280,720],[20,720],[0,720],[0,700]];
assert.deepEqual(context.simplifyFloorPoints(redundant),[[0,0],[1280,0],[1280,720],[0,720]]);
